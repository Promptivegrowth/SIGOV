-- ═══════════════════════════════════════════════════════════════════════
-- 0112 · Consolidado del tercer entregable (Elvis, 01/11/2026),
--        Observaciones de campo
--
-- REV3-OBS-34: varias actividades en un mismo punto. Cada actividad es su
--   propia observación (se programa y se exporta por separado), pero las del
--   mismo punto comparten punto_id: un solo marcador y las mismas fotos.
-- REV3-OBS-36: la progresiva manda. Si el tramo enviado no contiene la
--   progresiva, la base toma el tramo que sí la contiene antes de ubicar el
--   punto (el 1130+221 había quedado en el tramo 1, cerca de Arequipa).
-- REV3-OBS-37: se guarda el GPS real del teléfono, y la vista dice a cuántos
--   metros quedó de la progresiva registrada.
-- REV3-OBS-40: un ID único legible por observación (OBS-00001).
-- ═══════════════════════════════════════════════════════════════════════

alter table public.observaciones_campo
  add column if not exists punto_id uuid,
  add column if not exists gps_lat double precision,
  add column if not exists gps_lng double precision,
  add column if not exists gps_precision_m real,
  add column if not exists numero integer generated by default as identity;

create index if not exists observaciones_campo_punto on public.observaciones_campo (punto_id) where punto_id is not null;

-- ─── El punto sobre la vía: tramo por progresiva ──────────────────────
create or replace function public.t_observacion_ubicar()
returns trigger
language plpgsql
security definer
set search_path to 'public', 'extensions'
as $$
declare
  s public.road_sections;
  otro public.road_sections;
  p extensions.geometry;
begin
  if new.progresiva_m is not null then
    select * into s from public.road_sections where id = new.section_id;
    -- El tramo que no contiene la progresiva no es el tramo
    if s.id is null or new.progresiva_m < s.prog_start_m or new.progresiva_m > s.prog_end_m then
      select * into otro from public.road_sections
       where service_id = new.service_id and deleted_at is null
         and new.progresiva_m between prog_start_m and prog_end_m
       order by (geom is null), code
       limit 1;
      if otro.id is not null then
        new.section_id := otro.id;
        s := otro;
      end if;
    end if;
  end if;

  -- La cuadrilla escribe el km; el mapa lo ubica. Sin progresiva vale el
  -- punto que mandó el teléfono.
  if new.progresiva_m is not null and (
       tg_op = 'INSERT'
       or new.progresiva_m is distinct from old.progresiva_m
       or new.section_id is distinct from old.section_id
       or new.lat is null) then
    if s.id is not null and s.geom is not null and s.prog_end_m > s.prog_start_m then
      p := extensions.ST_LineInterpolatePoint(s.geom,
             least(0.999, greatest(0.001, (new.progresiva_m - s.prog_start_m) / (s.prog_end_m - s.prog_start_m))));
      new.lat := extensions.ST_Y(p);
      new.lng := extensions.ST_X(p);
    end if;
  end if;
  if new.lat is null and new.gps_lat is not null then
    new.lat := new.gps_lat;
    new.lng := new.gps_lng;
  end if;

  if new.estado = 'atendida' and (tg_op = 'INSERT' or old.estado <> 'atendida') then
    new.atendida_at := now();
    new.atendida_por := auth.uid();
  end if;
  if new.estado = 'programada' and new.programada_on is null then
    new.programada_on := (now() at time zone 'America/Lima')::date;
  end if;
  new.updated_at := now();
  return new;
end $$;

-- Las que ya están mal ubicadas se corrigen con la misma regla
update public.observaciones_campo o
   set section_id = s.id, lat = null
  from public.road_sections s
 where o.deleted_at is null and o.progresiva_m is not null
   and s.service_id = o.service_id and s.deleted_at is null
   and o.progresiva_m between s.prog_start_m and s.prog_end_m
   and o.section_id is distinct from s.id
   and not exists (select 1 from public.road_sections x
                    where x.id = o.section_id and o.progresiva_m between x.prog_start_m and x.prog_end_m);

-- ─── La vista ─────────────────────────────────────────────────────────
-- Las fotos son las del punto: las comparten las actividades del mismo sitio
create or replace view public.v_observaciones_campo with (security_invoker = true) as
select o.id, o.client_id, o.service_id, o.crew_id, c.name as crew_name,
       o.section_id, s.code as section_code, s.name as section_name, s.numero as section_numero,
       o.progresiva_m, public.fmt_progresiva(o.progresiva_m) as progresiva_txt, o.side,
       o.descripcion, o.estado, o.lat, o.lng, o.observado_on, o.programada_on,
       o.atendida_at, o.nota_atencion, o.created_by, pr.full_name as created_by_name, o.created_at,
       coalesce((select array_agg(e.storage_path order by e.taken_at, e.id)
                   from public.evidences e
                   join public.observaciones_campo h on h.id = e.observacion_id
                  where coalesce(h.punto_id, h.id) = coalesce(o.punto_id, o.id) and e.deleted_at is null), '{}') as fotos,
       o.activity_id, a.code as activity_code, a.name as activity_name, a.category as activity_category,
       u.symbol as unit_symbol,
       o.progresiva_fin_m, public.fmt_progresiva(o.progresiva_fin_m) as progresiva_fin_txt,
       o.metrado, o.plan_item_id,
       (select ss.code from public.service_sectors ss
         where ss.section_id = o.section_id and o.progresiva_m >= ss.prog_start_m and o.progresiva_m <= ss.prog_end_m
         order by ss.orden limit 1) as sector_code,
       coalesce((select array_agg(coalesce(e.client_id, e.id)::text order by e.taken_at, e.id)
                   from public.evidences e
                   join public.observaciones_campo h on h.id = e.observacion_id
                  where coalesce(h.punto_id, h.id) = coalesce(o.punto_id, o.id) and e.deleted_at is null), '{}') as fotos_ids,
       coalesce(o.punto_id, o.id) as punto_id,
       'OBS-' || lpad(o.numero::text, 5, '0') as codigo,
       o.gps_lat, o.gps_lng, o.gps_precision_m,
       case when o.gps_lat is not null and o.lat is not null and o.progresiva_m is not null then
         round(extensions.ST_Distance(
           extensions.ST_SetSRID(extensions.ST_MakePoint(o.gps_lng, o.gps_lat), 4326)::extensions.geography,
           extensions.ST_SetSRID(extensions.ST_MakePoint(o.lng, o.lat), 4326)::extensions.geography))::int
       end as gps_distancia_m
  from public.observaciones_campo o
  left join public.crews c on c.id = o.crew_id
  left join public.road_sections s on s.id = o.section_id
  left join public.profiles pr on pr.id = o.created_by
  left join public.activities_catalog a on a.id = o.activity_id
  left join public.units u on u.id = a.unit_id
 where o.deleted_at is null;

grant select on public.v_observaciones_campo to authenticated;

-- ─── Quitar una: las fotos del punto se quedan con las que siguen ─────
create or replace function public.quitar_observacion(p_client_id uuid default null, p_id uuid default null)
returns void
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  o public.observaciones_campo;
  v_estado public.plan_item_status;
  v_heredera uuid;
begin
  select * into o from public.observaciones_campo
   where (p_id is not null and id = p_id) or (p_client_id is not null and client_id = p_client_id)
   limit 1;
  if o.id is null or o.deleted_at is not null then return; end if;

  if not (public.can_manage(o.service_id) or (o.created_by = auth.uid() and o.estado = 'pendiente')) then
    raise exception 'SIGOV: solo quien la registró (mientras siga pendiente) o el supervisor pueden quitarla'
      using errcode = '42501';
  end if;

  if o.plan_item_id is not null then
    select status into v_estado from public.plan_items where id = o.plan_item_id and deleted_at is null;
    if v_estado is not null and v_estado not in ('programado', 'reprogramado', 'cancelado') then
      raise exception 'SIGOV: la observación ya se está atendiendo en la programación; no se puede quitar';
    end if;
    update public.plan_items set deleted_at = now() where id = o.plan_item_id and deleted_at is null;
  end if;

  update public.observaciones_campo set deleted_at = now() where id = o.id;

  -- Otra actividad del mismo punto se queda con las fotos
  select id into v_heredera from public.observaciones_campo
   where deleted_at is null and coalesce(punto_id, id) = coalesce(o.punto_id, o.id) and id <> o.id
   order by created_at limit 1;
  if v_heredera is not null then
    update public.evidences set observacion_id = v_heredera where observacion_id = o.id and deleted_at is null;
  else
    update public.evidences set deleted_at = now() where observacion_id = o.id and deleted_at is null;
  end if;
end $$;
